int n; string s; int a[maxm], len;
int min(int a, int b) { return a <= b ? a : b; }
void Raze()
{
    vector<vii>mp(17); cin >> n >> s;
    for (int i = 0; i < 17; i++)cin >> a[i];
    cin >> len; vector<string>tmp; if (len & 1)len++;
    if (len > n) { cout << "0" << endl; return; }
    for (int i = 0; i + len <= n; i++)
    {
        string x = s.substr(i, len);
        bool f=0;
        for (int k=0;k<len/2;k++){
            if (x[k]==x[len-k-1]) {
                f=1;
                break;
            }
        }
        if (!f) tmp.pb(x);
    }
    for (int i = 0; i < 16; i++)
    {
        char c = 'a' + i;
        for (int j = 0; j < tmp.size(); j++)
        {
            for (int k = 0; k < len / 2; k++)
            {
                {
                    if (tmp[j][k] == c)
                    {
                        if (tmp[j][len - k - 1] > c) { mp[i].pb(j); break; }
                    }
                    if (tmp[j][len - k - 1] == c)
                    {
                        if (tmp[j][k] > c) { mp[i].pb(j); break; }
                    }
                }
            }
        }
    }
    int ans =INF; //debug(tmp.size());
    for (int i = 0; i < (1ll << 16); i++)
    {
        int sum = 0; int tot = 0; vii vis(tmp.size(), 0);
        for (int j = 0; j < 16; j++)
        {
            if ((i >> j) & 1)
            {
                sum += a[j];
                for (int k : mp[j])
                {
                    if (!vis[k]) { tot++; vis[k] = 1; }
                    if (tot ==tmp.size())break;
                }
            }
            if (tot == tmp.size())break;
            if ((1ll << j) > i)break;
        }
        if (tot == tmp.size())ans = min(ans, sum);
    }
    cout << ans << endl;
}

signed main()
{
    ios::sync_with_stdio(false); cin.tie(nullptr); int _ = 1;
    cin >> _;
    while (_--)Raze(); return 0;
}
