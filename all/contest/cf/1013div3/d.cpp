void solve()
{
    int n,m,k;
    cin>>n>>m>>k;
    int cnt=(k+n-1)/n;
    int l=1,r=k;
    int ans=-1;
    while (l<=r){
        int mid=(l+r)>>1;
        if (cnt+(cnt+mid-1)/mid-1<=m){
            ans=mid;
            r=mid-1;
        }else l=mid+1;
    }
    cout<<ans<<endl;
}
